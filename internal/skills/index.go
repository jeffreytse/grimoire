package skills

import (
	"fmt"
	"sort"
	"strings"
)

// GenerateIndex builds a compact _GRIMOIRE_INDEX.md listing all installed skills
// grouped by domain/subdomain. Intended to be written alongside symlinks so AI
// assistants can discover available skills without reading every SKILL.md.
func GenerateIndex(regs []SkillsPackage) (string, error) {
	all, _, err := ListAllSkillsFromPackages(regs)
	if err != nil {
		return "", err
	}
	return buildIndexContent(all), nil
}

func buildIndexContent(all []Skill) string {
	type group struct {
		key    string
		skills []Skill
	}

	seen := map[string]*group{}
	var order []string

	for i := range all {
		sk := &all[i]
		key := sk.Domain
		if sk.Subdomain != "" {
			key = sk.Domain + "/" + sk.Subdomain
		}
		if _, ok := seen[key]; !ok {
			seen[key] = &group{key: key}
			order = append(order, key)
		}
		seen[key].skills = append(seen[key].skills, *sk)
	}
	sort.Strings(order)

	var sb strings.Builder
	sb.WriteString("# Grimoire Skills Index\n\n")
	sb.WriteString("<!-- generated by grimoire install — do not edit manually -->\n\n")

	for _, key := range order {
		g := seen[key]
		fmt.Fprintf(&sb, "## %s\n\n", key)
		sort.Slice(g.skills, func(i, j int) bool {
			return g.skills[i].Name < g.skills[j].Name
		})
		for i := range g.skills {
			sk := &g.skills[i]
			desc := sk.Description
			if desc == "" {
				desc = "(no description)"
			}
			fmt.Fprintf(&sb, "- **%s**: %s\n", sk.Name, desc)
		}
		sb.WriteString("\n")
	}
	return sb.String()
}
